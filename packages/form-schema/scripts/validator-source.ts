import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

export const CONTRACT_PATH = fileURLToPath(new URL("../../../contracts/form-definition.schema.json", import.meta.url));

/** Ajv's CommonJS runtime helpers, swapped for the local ESM equivalents in src/generated/runtime.js. */
const RUNTIME_REPLACEMENTS: Record<string, string> = {
  'require("ajv/dist/runtime/ucs2length").default': "ucs2length",
  'require("ajv/dist/runtime/equal").default': "equal",
};

/** Generated module source for the structural validator. Deterministic for a given contract and Ajv version. */
export function generateValidatorSource(): string {
  const schema = JSON.parse(readFileSync(CONTRACT_PATH, "utf8")) as Record<string, unknown>;
  const ajv = new Ajv2020({
    code: { source: true, esm: true },
    strict: true,
    // The contract's conditional `then` blocks require settings that are
    // declared on the parent settings schema; that is intended.
    strictRequired: false,
    allowUnionTypes: true,
    allErrors: true,
  });
  let code = standaloneCode(ajv, ajv.compile(schema));
  for (const [from, to] of Object.entries(RUNTIME_REPLACEMENTS)) code = code.replaceAll(from, to);
  if (code.includes("require(")) {
    throw new Error("Generated validator still references a CommonJS runtime helper; extend RUNTIME_REPLACEMENTS.");
  }
  return [
    "// @ts-nocheck",
    "/* eslint-disable */",
    "// GENERATED by packages/form-schema/scripts/generate-validator.ts from",
    "// contracts/form-definition.schema.json. Do not edit by hand.",
    'import { equal, ucs2length } from "./runtime.js";',
    code.replace(/^"use strict";/, ""),
    "",
  ].join("\n");
}
